const GLYPH_W: usize = 5;
const GLYPH_H: usize = 7;
pub const SCALE: usize = 2;
pub const CELL_W: usize = (GLYPH_W + 1) * SCALE;
pub const CELL_H: usize = (GLYPH_H + 1) * SCALE;

