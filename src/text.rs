pub fn rasterize(text: &str, width: usize, height: usize) -> Vec<u8> {
    let mut img = vec![0u8; width * height];
    for (line_no, line) in text.lines().enumerate() {
        for (ci, c) in line.chars().enumerate() {
            let g = glyph(c);
            for (row, bits) in g.iter().enumerate() {
                for col in 0..GLYPH_W {
                    if bits & (0x10 >> col) == 0 {
                        continue;
                    }
                    for dy in 0..SCALE {
                        for dx in 0..SCALE {
                            let x = ci * CELL_W + col * SCALE + dx;
                            let y = line_no * CELL_H + row * SCALE + dy;
                            if x < width && y < height {
                                img[y * width + x] = 255;
                            }
                        }
                    }
                }
            }
        }
    }
    img
}
